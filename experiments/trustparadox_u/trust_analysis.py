def cochrans_q(outcomes: Sequence[Sequence[bool]]) -> dict[str, Any] | None:
    """Cochran's Q over complete families (rows) x trust levels (columns)."""
    if not outcomes:
        return None
    k = len(outcomes[0])
    n = len(outcomes)
    if k < 2 or any(len(row) != k for row in outcomes):
        return None
    col_sums = [sum(1 for row in outcomes if row[j]) for j in range(k)]
    row_sums = [sum(row) for row in outcomes]
    total = sum(col_sums)
    denominator = k * total - sum(r * r for r in row_sums)
    if denominator == 0:
        return {"statistic": None, "df": k - 1, "n_families": n, "note": "degenerate denominator"}
    numerator = (k - 1) * (k * sum(g * g for g in col_sums) - total * total)
    return {
        "statistic": numerator / denominator,
        "df": k - 1,
        "n_families": n,
        "columns": list(TRUST_LEVELS[:k]),
    }


def _rate(numerator: int, denominator: int) -> float | None:
    # SC-012: non-evaluable values serialize as null, never fabricated zeroes.
    if denominator <= 0:
        return None
    return numerator / denominator


