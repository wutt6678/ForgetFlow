def _family_outcomes(
    family: CandidateFamily,
    condition: str,
    trial_index: dict[tuple[str, str], dict[str, Any]],
    audit_actions: dict[tuple[str, str], str],
    audit_evidence: dict[tuple[str, str], str | None],
    utility_index: dict[tuple[str, str], dict[str, Any]],
) -> tuple[dict[str, Any] | None, str | None]:
    """Per-trust outcomes for one family under one condition.

    Returns (outcomes, exclusion_reason).  Successful replay under every
    trust level is required (SC-005 eligibility).
    """
    exposure: dict[str, bool] = {}
    action: dict[str, str | None] = {}
    evidence: dict[str, str | None] = {}
    utility: dict[str, tuple[bool, bool] | None] = {}
    for trust in TRUST_LEVELS:
        member = family.member_for(trust)
        if member is None:
            return None, f"missing_trust_level:{trust}"
        trial = trial_index.get((condition, member.candidate_id))
        if trial is None:
            return None, f"missing_trial:{trust}"
        if trial.get("result_status") != "success":
            return None, f"failed_replay:{trust}"
        labels = trial.get("released_exposure_labels") or []
        exposure[trust] = any(label in _POSITIVE_EXPOSURE_LABELS for label in labels)
        audit_key = (condition, member.candidate_id)
        action[trust] = audit_actions.get(audit_key)
        evidence[trust] = audit_evidence.get(audit_key)
        utility_trial = utility_index.get((condition, member.candidate_id))
        if utility_trial is None:
            utility[trust] = None
        else:
            utility[trust] = (
                bool(utility_trial.get("firewall_task_success", False)),
                bool(utility_trial.get("firewall_blocked", False)),
            )
    return {"exposure": exposure, "action": action, "evidence": evidence, "utility": utility}, None


def _panel_a_row(
    condition: str,
    attack_population: str,
    pairing_unit: str,
    paired: list[dict[str, Any]],
    excluded_count: int,
) -> dict[str, Any]:
    """Assemble one Panel A row from family-level paired outcomes."""
    n = len(paired)
    exposure_matrix = [[p["exposure"][t] for t in TRUST_LEVELS] for p in paired]
    rates = {
        trust: _rate(sum(1 for p in paired if p["exposure"][trust]), n) for trust in TRUST_LEVELS
    }
    differences = [int(p["exposure"]["high"]) - int(p["exposure"]["low"]) for p in paired]
    risk_difference = _rate(sum(differences), n) if n else None

    if n:
        b = sum(1 for d in differences if d > 0)  # high+ / low-
        c = sum(1 for d in differences if d < 0)  # high- / low+
        p_value: float | None = exact_mcnemar_test(b, c)["p_value"]
        permutation_p = paired_permmutation_test(differences)["p_value"]
        clusters = [p["secret_variant_id"] for p in paired]
        bootstrap = cluster_bootstrap_ci(differences, clusters, cluster_unit="secret_variant_id")
        ci95: dict[str, Any] | None = {
            "lower": bootstrap["lower"],
            "upper": bootstrap["upper"],
            "method": "cluster_bootstrap",
            "cluster_unit": "secret_variant_id",
        }
    else:
        p_value, permutation_p, ci95 = None, None, None

    def _disagreement(selector: Any) -> float | None:
        values = [tuple(selector(p)[t] for t in TRUST_LEVELS) for p in paired]
        evaluable = [v for v in values if all(x is not None for x in v)]
        if not evaluable:
            return None
        return sum(1 for v in evaluable if len(set(v)) > 1) / len(evaluable)

    # Strict invariance: exposure labels AND policy actions equal across
    # all three trust levels (actions must all be observed).
    strict_pairs = [p for p in paired if all(p["action"][t] is not None for t in TRUST_LEVELS)]
    strict_invariance = (
        sum(
            1
            for p in strict_pairs
            if len({p["exposure"][t] for t in TRUST_LEVELS}) == 1
            and len({p["action"][t] for t in TRUST_LEVELS}) == 1
        )
        / len(strict_pairs)
        if strict_pairs
        else None
    )
    # Privacy invariance: only whether unauthorized exposure occurred.
    privacy_invariance = (
        sum(1 for p in paired if len({p["exposure"][t] for t in TRUST_LEVELS}) == 1) / n
        if n
        else None
    )

    return {
        "condition": condition,
        "attack_population": attack_population,
        "pairing_unit": pairing_unit,
        "complete_families": n,
        "excluded_families": excluded_count,
        "low_rate": rates["low"],
        "default_rate": rates["default"],
        "high_rate": rates["high"],
        "low_high_risk_difference": risk_difference,
        "ci95": ci95,
        "paired_p_value": p_value,
        "permutation_p_value": permutation_p,
        "action_disagreement_rate": _disagreement(lambda p: p["action"]),
        "target_evidence_disagreement_rate": _disagreement(lambda p: p["evidence"]),
        "utility_disagreement_rate": _disagreement(lambda p: p["utility"]),
        "strict_invariance_rate": strict_invariance,
        "privacy_invariance_rate": privacy_invariance,
        "cochran_q": cochrans_q(exposure_matrix) if n else None,
        "interpretation": PANEL_A_INTERPRETATION,
    }


def compute_rq6_panel(
    inputs: dict[str, Any],
    conditions: Sequence[str],
) -> dict[str, Any]:
    """Panel A rows + pairing audit for the requested conditions."""
    candidates: list[FrozenCandidate] = inputs["candidates"]
    families, family_exclusions = index_candidate_families(candidates)
    complete_families, content_exclusions = classify_rq6_families(families)
    seq_families, seq_exclusions = index_sequence_families(candidates)

    trial_index: dict[tuple[str, str], dict[str, Any]] = {}
    for trial in inputs["candidate_trials"]:
        trial_index[(str(trial.get("condition_id", "")), str(trial.get("candidate_id", "")))] = (
            trial
        )
    utility_index: dict[tuple[str, str], dict[str, Any]] = {}
    for trial in inputs["utility_trials"]:
        utility_index[
            (str(trial.get("firewall_condition", "")), str(trial.get("candidate_id", "")))
        ] = trial

    audit_actions = inputs["audit_actions"]
    audit_evidence = inputs["audit_evidence"]

    rows: list[dict[str, Any]] = []
    condition_exclusions: list[dict[str, Any]] = []

    attacks = sorted({f.attack_type for f in families.values()})
    for condition in conditions:
        for attack in attacks:
            paired: list[dict[str, Any]] = []
            for family in sorted(
                (f for f in complete_families.values() if f.attack_type == attack),
                key=lambda f: f.family_id,
            ):
                outcomes, reason = _family_outcomes(
                    family, condition, trial_index, audit_actions, audit_evidence, utility_index
                )
                if outcomes is None:
                    condition_exclusions.append(
                        {
                            "family_id": family.family_id,
                            "condition": condition,
                            "reason": reason,
                        }
                    )
                    continue
                paired.append(
                    {
                        "family_id": family.family_id,
                        "secret_variant_id": family.secret_variant_id,
                        **outcomes,
                    }
                )
            excluded_count = sum(
                1
                for e in family_exclusions + content_exclusions
                if families.get(e["family_id"], None) is not None
                and families[e["family_id"]].attack_type == attack
            ) + sum(
                1
                for e in condition_exclusions
                if e["condition"] == condition
                and complete_families.get(e["family_id"]) is not None
                and complete_families[e["family_id"]].attack_type == attack
            )
            rows.append(
                _panel_a_row(condition, attack, "candidate_family_id", paired, excluded_count)
            )

    # Sequence families pair on sequence_family_id (SC-002).
    seq_trial_index: dict[tuple[str, str], list[dict[str, Any]]] = {}
    for trial in inputs["reconstruction_trials"]:
        family_id = str(trial.get("sequence_family_id", ""))
        if family_id:
            seq_trial_index.setdefault((str(trial.get("condition", "")), family_id), []).append(
                trial
            )
    for condition in conditions:
        paired_seq: list[dict[str, Any]] = []
        for seq_family in sorted(seq_families.values(), key=lambda f: f.family_id):
            recovered: dict[str, bool | None] = {}
            seq_reason: str | None = None
            for trust in TRUST_LEVELS:
                trust_seqs = [s for s, t in seq_family.sequence_trust.items() if t == trust]
                trials = [
                    trial
                    for s in trust_seqs
                    for trial in seq_trial_index.get((condition, seq_family.family_id), [])
                    if trial.get("sequence_id") == s
                ]
                if not trials:
                    seq_reason = f"missing_trial:{trust}"
                    break
                if not any(trial.get("eligible") for trial in trials):
                    seq_reason = f"failed_replay:{trust}"
                    break
                recovered[trust] = any(trial.get("recovered") for trial in trials)
            if seq_reason is not None:
                condition_exclusions.append(
                    {
                        "family_id": seq_family.family_id,
                        "condition": condition,
                        "reason": seq_reason,
                    }
                )
                continue
            paired_seq.append(
                {
                    "family_id": seq_family.family_id,
                    "secret_variant_id": seq_family.secret_variant_id,
                    "exposure": {t: bool(recovered[t]) for t in TRUST_LEVELS},
                    "action": {t: None for t in TRUST_LEVELS},
                    "evidence": {t: None for t in TRUST_LEVELS},
                    "utility": {t: None for t in TRUST_LEVELS},
                }
            )
        if paired_seq or seq_families:
            excluded_seq = len(seq_exclusions) + sum(
                1
                for e in condition_exclusions
                if e["condition"] == condition and e["family_id"] in seq_families
            )
            rows.append(
                _panel_a_row(
                    condition,
                    "multi_step_reconstruction",
                    "sequence_family_id",
                    paired_seq,
                    excluded_seq,
                )
            )

    pairing_audit = {
        "pairing_units": {
            "single_message": "candidate_family_id",
            "sequence": "sequence_family_id",
        },
        "candidate_families_total": len(families) + len(family_exclusions),
        "candidate_families_complete": len(complete_families),
        "sequence_families_total": len(seq_families) + len(seq_exclusions),
        "exclusions": family_exclusions + content_exclusions + seq_exclusions,
        "condition_exclusions": condition_exclusions,
    }
    return {"rows": rows, "pairing_audit": pairing_audit}


