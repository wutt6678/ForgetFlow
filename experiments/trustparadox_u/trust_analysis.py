def build_rq7_manipulation_panel(
    generation_models: Sequence[str], *, study_class: str = "diagnostic"
) -> dict[str, Any]:
    """SC-006 RQ7 scaffold.

    Deterministic-template generation can never become evaluable: Panel B
    reports the explicit non-evaluable benchmark instead.  Empirical
    calculations activate only when provenance identifies valid empirical
    (trust-conditioned) generation.
    """
    models = {m for m in generation_models if m}
    deterministic = models <= {DETERMINISTIC_TEMPLATE_MODEL}
    if deterministic:
        return {
            "definition": "Pre-enforcement candidate-generation behavior by trust level.",
            "study_class": "diagnostic",
            "evaluable": False,
            "reason": RQ7_SCHEMA_REASON,
            "deterministic_benchmark": dict(RQ7_DETERMINISTIC_BENCHMARK),
            "rows": [],
        }
    return {
        "definition": "Pre-enforcement candidate-generation behavior by trust level.",
        "study_class": study_class,
        "evaluable": True,
        "reason": None,
        "generation_models": sorted(models),
        "required_outcomes": [
            "unauthorized_disclosure_rate",
            "exact_value_disclosure_rate",
            "semantic_disclosure_rate",
            "refusal_rate",
            "task_compliance_rate",
            "candidate_length",
        ],
        "cluster_unit": "scenario x secret variant x attack family x generation replicate",
        "rows": [],
    }


