@dataclass(frozen=True)
class FamilyMember:
    """One trust-level member of a candidate family."""

    candidate_id: str
    trust_level: str
    content_hash: str
    generation_replicate: int = 0


@dataclass(frozen=True)
class CandidateFamily:
    """SC-001: content-identical candidates differing only in trust label."""

    family_id: str
    scenario_id: str
    secret_variant_id: str
    attack_type: str
    sample_index: int
    members: tuple[FamilyMember, ...]

    def member_for(self, trust_level: str) -> FamilyMember | None:
        for member in self.members:
            if member.trust_level == trust_level:
                return member
        return None


@dataclass(frozen=True)
class SequenceFamily:
    """SC-002: multi-step sequences differing only in trust label."""

    family_id: str
    scenario_id: str
    secret_variant_id: str
    attack_type: str
    step_count: int
    # sequence_id -> trust level for every member step record.
    sequence_trust: dict[str, str]


def index_candidate_families(
    candidates: Sequence[FrozenCandidate],
) -> tuple[dict[str, CandidateFamily], list[dict[str, Any]]]:
    """Group single-message candidates by candidate_family_id.

    Returns (families, exclusions); every exclusion carries a reason
    (SC-005: exclusions are visible).
    """
    raw: dict[str, list[FrozenCandidate]] = {}
    for c in candidates:
        if c.candidate_family_id and not c.sequence_id:
            raw.setdefault(c.candidate_family_id, []).append(c)

    families: dict[str, CandidateFamily] = {}
    exclusions: list[dict[str, Any]] = []
    for family_id, members in sorted(raw.items()):
        first = members[0]
        if any(
            m.scenario_id != first.scenario_id
            or m.secret_variant_id != first.secret_variant_id
            or m.attack_type != first.attack_type
            or m.sample_index != first.sample_index
            for m in members
        ):
            exclusions.append({"family_id": family_id, "reason": "mixed_identity_fields"})
            continue
        seen_trust: dict[tuple[str, int], str] = {}
        duplicate = False
        for m in members:
            key = (m.trust_level, m.generation_replicate)
            if key in seen_trust:
                exclusions.append(
                    {
                        "family_id": family_id,
                        "reason": f"duplicate_trust_member:{m.trust_level}",
                    }
                )
                duplicate = True
                break
            seen_trust[key] = m.candidate_id
        if duplicate:
            continue
        families[family_id] = CandidateFamily(
            family_id=family_id,
            scenario_id=first.scenario_id,
            secret_variant_id=first.secret_variant_id,
            attack_type=first.attack_type,
            sample_index=first.sample_index,
            members=tuple(
                FamilyMember(
                    candidate_id=m.candidate_id,
                    trust_level=m.trust_level,
                    content_hash=m.content_hash,
                    generation_replicate=m.generation_replicate,
                )
                for m in sorted(members, key=lambda x: (x.trust_level, x.generation_replicate))
            ),
        )
    return families, exclusions


def index_sequence_families(
    candidates: Sequence[FrozenCandidate],
) -> tuple[dict[str, SequenceFamily], list[dict[str, Any]]]:
    """Group multi-step sequence records by sequence_family_id."""
    raw: dict[str, list[FrozenCandidate]] = {}
    for c in candidates:
        if c.sequence_family_id and c.sequence_id:
            raw.setdefault(c.sequence_family_id, []).append(c)

    families: dict[str, SequenceFamily] = {}
    exclusions: list[dict[str, Any]] = []
    for family_id, members in sorted(raw.items()):
        first = members[0]
        if any(
            m.scenario_id != first.scenario_id
            or m.secret_variant_id != first.secret_variant_id
            or m.attack_type != first.attack_type
            or m.sequence_step_count != first.sequence_step_count
            for m in members
        ):
            exclusions.append({"family_id": family_id, "reason": "mixed_identity_fields"})
            continue
        positions = {m.sequence_step_index for m in members}
        if positions != set(range(first.sequence_step_count)):
            exclusions.append(
                {
                    "family_id": family_id,
                    "reason": (
                        f"incomplete_step_positions:{sorted(positions)} != "
                        f"0..{first.sequence_step_count - 1}"
                    ),
                }
            )
            continue
        sequence_trust = {m.sequence_id: m.trust_level for m in members if m.sequence_id}
        families[family_id] = SequenceFamily(
            family_id=family_id,
            scenario_id=first.scenario_id,
            secret_variant_id=first.secret_variant_id,
            attack_type=first.attack_type,
            step_count=first.sequence_step_count,
            sequence_trust=sequence_trust,
        )
    return families, exclusions


def classify_rq6_families(
    families: dict[str, CandidateFamily],
) -> tuple[dict[str, CandidateFamily], list[dict[str, Any]]]:
    """SC-003/SC-005 eligibility: complete trust coverage + identical content.

    RQ6 eligibility requires ``len({member.content_hash}) == 1``; every
    excluded family is recorded with a reason.
    """
    complete: dict[str, CandidateFamily] = {}
    exclusions: list[dict[str, Any]] = []
    for family_id, family in sorted(families.items()):
        present = {m.trust_level for m in family.members}
        missing = [t for t in TRUST_LEVELS if t not in present]
        if missing:
            exclusions.append(
                {"family_id": family_id, "reason": f"missing_trust_level:{','.join(missing)}"}
            )
            continue
        hashes = {m.content_hash for m in family.members}
        if len(hashes) != 1 or "" in hashes:
            exclusions.append({"family_id": family_id, "reason": "content_hash_mismatch"})
            continue
        complete[family_id] = family
    return complete, exclusions


