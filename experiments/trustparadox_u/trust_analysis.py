def panel_a_conditions(resolved_conditions: dict[str, Any]) -> list[str]:
    """full_mvp minimum + secondary conditions present in the replay."""
    available = set(resolved_conditions) if resolved_conditions else set()
    conditions = [PANEL_A_MINIMUM_CONDITION]
    conditions.extend(c for c in PANEL_A_SECONDARY_CONDITIONS if c in available)
    return conditions


def build_trust_analysis_payload(
    inputs: dict[str, Any], conditions: Sequence[str]
) -> dict[str, Any]:
    panel_a = compute_rq6_panel(inputs, conditions)
    generation_models = [str(c.generation_model) for c in inputs["candidates"]]
    panel_b = build_rq7_manipulation_panel(generation_models)
    return {
        "analysis": "trust_analysis",
        "schema_version": "1.0",
        "protocol_version": PROTOCOL_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "conditions": list(conditions),
        "panel_a": panel_a,
        "panel_b": panel_b,
    }


def write_trust_analysis(payload: dict[str, Any], output_dir: Path) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "trust_analysis.json").write_text(json.dumps(payload, indent=2))
    (output_dir / "pairing_audit.json").write_text(
        json.dumps(payload["panel_a"]["pairing_audit"], indent=2)
    )


def main() -> int:
    """SC-006: run the trust analysis over frozen replay trial artifacts."""
    print("SC-006: Trust Analysis (Table 6 inputs)")
    print("=" * 40)
    inputs = load_trust_inputs()
    conditions = panel_a_conditions(inputs["resolved_conditions"])
    payload = build_trust_analysis_payload(inputs, conditions)
    write_trust_analysis(payload, TRUST_ANALYSIS_DIR)
    rows = payload["panel_a"]["rows"]
    print(f"  Panel A rows: {len(rows)} across conditions {conditions}")
    for row in rows:
        print(
            f"  {row['condition']} / {row['attack_population']} "
            f"({row['pairing_unit']}): complete={row['complete_families']} "
            f"excluded={row['excluded_families']}"
        )
    print(f"  Panel B evaluable: {payload['panel_b']['evaluable']}")
    print(f"  Written to {TRUST_ANALYSIS_DIR}")
    return 0


